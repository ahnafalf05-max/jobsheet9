public class ArrayBilangan1 {
    public static void main(String[] args) {
        // Inisialisasi array langsung saat deklarasi
        int[] bil = {5, 13, -7, 17};

        // Menampilkan isi array menggunakan perulangan
        for (int i = 0; i < 4; i++) {
            System.out.println(bil[i]);
        }
    }
}

